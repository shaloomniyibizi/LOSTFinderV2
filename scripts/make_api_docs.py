"""Write docs/API.md from the back end's own OpenAPI description, so the reference never drifts
from the code. Run from the project folder (needs the back-end requirements installed):

    python scripts/make_api_docs.py

The same information is live at http://localhost:8001/docs while the system runs.
"""
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))
os.environ.setdefault("DATABASE_URL", "sqlite://")
os.environ.setdefault("BACKGROUND_TASKS", "0")

from app.main import app  # noqa: E402

def who(op: dict, path: str) -> str:
    if "/replication/snapshot" in path:
        return "branches only"
    if path.startswith("/users") or "resync" in path or (path == "/items/{item_id}" and op.get("operationId", "").startswith("delete")):
        return "admin"
    if path in ("/claims",) or path.startswith("/claims/{claim_id}/"):
        return "staff, admin"
    if op.get("security"):
        return "signed in"
    return "anyone"


def main():
    spec = app.openapi()
    groups: dict[str, list] = {}
    for path, methods in spec["paths"].items():
        for method, op in methods.items():
            tag = (op.get("tags") or ["other"])[0]
            first = (op.get("description") or op.get("summary") or "").strip().split("\n")[0]
            body = op.get("requestBody", {}).get("content", {})
            schema = next(iter(body.values()), {}).get("schema", {}).get("$ref", "").split("/")[-1] if body else ""
            if "multipart/form-data" in body:
                schema = "file upload"
            elif "application/x-www-form-urlencoded" in body:
                schema = "form fields"
            groups.setdefault(tag, []).append((path, method.upper(), who(op, path), first, schema))
    order = ["auth", "users (admin)", "items", "photos", "claims", "live", "stats", "branches", "health", "replication"]
    lines = [
        "# API reference",
        "",
        f"LostFinder {spec['info']['version']}. Every branch serves the same API: Campus `http://localhost:8001`, "
        "Bus Park `http://localhost:8002`, Airport `http://localhost:8003`. Interactive version with a *Try it out* "
        "button: `/docs` on any branch.",
        "",
        "Sign in with `POST /auth/login` (form fields `username` = email, `password`) and send the token as "
        "`Authorization: Bearer <token>`. A token works at every branch.",
        "",
        "*This file is generated by `scripts/make_api_docs.py`.*",
        "",
    ]
    for tag in sorted(groups, key=lambda t: order.index(t) if t in order else 99):
        lines += [f"## {tag.capitalize()}", "", "| Method | Path | Who | What | Body |", "|---|---|---|---|---|"]
        for path, method, w, first, schema in sorted(groups[tag]):
            lines.append(f"| {method} | `{path}` | {w} | {first.replace('|', '/')} | {schema} |")
        lines.append("")
    lines += ["## WebSocket", "", "| Path | Who | What |", "|---|---|---|",
              "| `ws://<branch>/ws?token=<token>` | signed in | Live notifications: matches and claim decisions |", ""]
    (ROOT / "docs" / "API.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote docs/API.md ({sum(len(v) for v in groups.values())} endpoints)")


if __name__ == "__main__":
    main()
